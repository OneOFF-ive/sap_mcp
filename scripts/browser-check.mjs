import { createRequire } from 'node:module';
import { mkdir, mkdtemp, rm } from 'node:fs/promises';
import { join } from 'node:path';
import { createServer } from 'node:net';
import assert from 'node:assert/strict';
import { ConfigStore } from '../dist/config.js';
import { startAdmin } from '../dist/admin.js';

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE ?? 'playwright');
const root = join(process.cwd(), '.sap-mcp', 'browser-check'); await mkdir(root, { recursive: true });
const directory = await mkdtemp(join(root, 'config-'));
const passwords = new Map();
const credentials = { get: async id => passwords.get(id), set: async (id, value) => passwords.set(id, value), remove: async id => passwords.delete(id) };
const runtime = await startAdmin(new ConfigStore(directory), credentials, 0, () => ({ capabilities: async () => ({ discovery: [{}] }), close: async () => {} }));
let browser;
try {
  browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE ? { executablePath: process.env.BROWSER_EXECUTABLE } : {}) });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(runtime.url); await page.locator('#connection-total').filter({ hasText: '0 个连接' }).waitFor();
  await page.getByRole('button', { name: '添加连接', exact: true }).first().click();
  await page.locator('[name=name]').fill('sap_system_01'); await page.locator('[name=base_url]').fill('http://sap.example:8000');
  await page.locator('[name=client]').fill('001'); await page.locator('[name=username]').fill('CONSULTANT');
  await page.locator('[name=password]').fill('synthetic-only');
  for (const name of ['bad.name', 'sap system', '中文系统']) {
    await page.locator('[name=name]').fill(name);
    await page.getByRole('button', { name: '保存连接', exact: true }).click();
    assert.ok((await page.locator('#form-error').textContent()).includes('不允许'));
    assert.equal(await page.locator('[name=name]').getAttribute('aria-invalid'), 'true');
    assert.equal(await page.locator('#connection-dialog').isVisible(), true);
  }
  await page.screenshot({ path: join(root, 'connection-validation.png'), fullPage: true });
  await page.locator('[name=name]').fill('sap_system_01');
  await page.locator('[name=base_url]').fill('http://sap.example:8000/unsupported');
  await page.getByRole('button', { name: '保存连接', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('#form-error').textContent.includes('ADT 地址必须'));
  assert.equal(await page.locator('[name=base_url]').getAttribute('aria-invalid'), 'true');
  assert.equal(await page.locator('[name=base_url]').evaluate(node => node === document.activeElement), true);
  assert.equal(await page.locator('[name=password]').inputValue(), '');
  await page.locator('[name=base_url]').fill('http://sap.example:8000');
  await page.locator('[name=password]').fill('synthetic-only');
  await page.getByRole('button', { name: '保存连接', exact: true }).click();
  await page.locator('#connection-rows strong').filter({ hasText: 'sap_system_01' }).waitFor();
  await page.getByRole('button', { name: '测试连接', exact: true }).click();
  await page.getByText('连接成功', { exact: true }).waitFor();
  await page.screenshot({ path: join(root, 'desktop.png'), fullPage: true });
  await page.getByRole('button', { name: '访问令牌', exact: true }).click();
  await page.getByRole('button', { name: '创建令牌', exact: true }).click();
  await page.locator('#token-dialog').waitFor({ state: 'visible' });
  assert.ok((await page.locator('#new-token').inputValue()).startsWith('Bearer '));
  await page.getByRole('button', { name: '完成', exact: true }).click();
  assert.equal(await page.locator('#new-token').inputValue(), '');
  await page.getByRole('button', { name: 'MCP 服务', exact: true }).click();
  const probe = createServer(); await new Promise(resolve => probe.listen(0, '127.0.0.1', resolve));
  const port = probe.address().port; await new Promise(resolve => probe.close(resolve));
  await page.locator('#port').fill(String(port)); await page.getByRole('button', { name: '启动服务', exact: true }).click();
  await page.locator('#service-status').filter({ hasText: '运行中' }).waitFor();
  await page.getByRole('button', { name: '系统连接', exact: false }).click();
  assert.equal(await page.locator('#add-connection').isDisabled(), true);
  await page.getByRole('button', { name: 'MCP 服务', exact: true }).click();
  await page.getByRole('button', { name: '停止服务', exact: true }).click();
  await page.locator('#confirm-action').click(); await page.locator('#service-status').filter({ hasText: '已停止' }).waitFor();
  await page.getByRole('button', { name: '系统连接', exact: false }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: join(root, 'mobile.png'), fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.getByRole('button', { name: '编辑连接', exact: true }).click();
  await page.screenshot({ path: join(root, 'mobile-form.png'), fullPage: true });
  assert.equal(await page.locator('[name=password]').inputValue(), '');
  assert.deepEqual(errors, []);
  console.log('Browser checks passed: connection form, test, token, service lifecycle, desktop/mobile; no page errors.');
  console.log(`Screenshots: ${root}`);
} finally { await browser?.close(); await runtime.close(); await rm(directory, { recursive: true, force: true }); }
